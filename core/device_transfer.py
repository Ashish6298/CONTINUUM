"""
Project Continuum — Offline Device Transfer Manager
===================================================
Milestone 43: Export, Backup, Import and Transfer
Phase 79: Device Transfer Guide

Implements:
1. 100% Offline, Local-First File-Based Transfer:
   - Zero network, cloud, server, account, or live sync requirements.
   - Encapsulates authoritative state, checkpoints, DAG relations, and configs into
     a single verifiable transfer archive (`.continuum-transfer.tar.gz`).
2. Version Compatibility Checks:
   - Explicit version negotiation: Compatible minor format versions (e.g. 1.0.0 vs 1.0.1)
     are accepted with audit logging; incompatible major versions (e.g. 2.0.0) are blocked.
3. Destination Missing Artifact Reconciliation:
   - When importing on a new device, files that existed only on the source device's
     local filesystem are detected and marked gracefully as `missing_on_device=True`
     without crashing, breaking DAG continuity, or corrupting state.
4. Comprehensive Package Inspection:
   - Inspects package contents, checksums, origin device metadata, and conflicts
     without modifying destination workspace.
5. Zero external dependencies (Python standard library only).
"""

