SUPPORTED_FORMAT_MAJOR = 1
SUPPORTED_FORMAT_VERSION = "1.0.0"


class DeviceTransferError(ContinuumUserError):
    """Base exception for all device transfer errors."""
    def __init__(self, message: str, internal_details: Optional[str] = None):
        super().__init__(
            user_message=f"Device transfer error: {message}",
            suggested_action="Ensure the transfer archive was generated by Continuum and is uncorrupted.",
            error_code="ERR_DEVICE_TRANSFER",
            internal_details=internal_details or message,
        )


class IncompatibleDeviceVersionError(DeviceTransferError):
    """Raised when transfer package has an incompatible major format version."""
    def __init__(self, found_version: str, supported_version: str):
        super().__init__(
            message=f"Unsupported package format version '{found_version}'. Supported: '{supported_version}'.",
            internal_details=f"Found: {found_version}, Supported: {supported_version}",
        )
        self.error_code = "ERR_TRANSFER_VERSION_INCOMPATIBLE"
        self.suggested_action = "Update Continuum on the destination device to match the source package version."


@dataclass
class TransferPackageInspection:
    """Metadata inspection summary of an offline transfer package."""
    package_path: str
    is_valid: bool
    format_version: str
    is_version_compatible: bool
    version_warning: Optional[str]
    source_platform: Dict[str, str]
    created_at: str
    total_activities: int
    total_checkpoints: int
    total_artifacts: int
    total_size_bytes: int
    file_manifest_count: int

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class TransferImportResult:
    """Outcome of importing a transfer package onto a destination device."""
    success: bool
    import_result: Dict[str, Any]
    missing_artifacts_detected: List[Dict[str, Any]] = field(default_factory=list)
    version_note: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class DeviceTransferManager:
    """
    Manages local-first, air-gapped device-to-device transfers for Project Continuum.
    Follows Phase 79 standards:
    - Pure file-based transfer (no network sync, accounts, or telemetry).
    - Multi-platform path normalization.
    - Missing artifact detection on new destination device.
    - Strict version compatibility enforcement.
    """

    def __init__(self, workspace_root: Union[str, Path]):
        self.workspace_root = Path(workspace_root).resolve()
        self.continuum_dir = self.workspace_root / ".continuum"
        self.backup_engine = CompleteBackupEngine(self.workspace_root)
        self.import_engine = CompleteImportEngine(self.workspace_root)
        self.store = ActivityCheckpointStore(str(self.workspace_root))

    def create_transfer_package(
        self,
        output_path: Optional[Union[str, Path]] = None,
        package_name: Optional[str] = None,
    ) -> Path:
        """
        Creates a standalone, self-verifying transfer archive for manual device transfer.
        """
        timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        name = package_name or f"continuum_transfer_{timestamp}.tar.gz"
        if not name.endswith(".tar.gz") and not name.endswith(".tgz"):
            name += ".tar.gz"

        backup_res = self.backup_engine.create_backup(
            output_path=output_path,
            backup_name=name,
        )
        return Path(backup_res.archive_path).resolve()

    def inspect_package(self, package_path: Union[str, Path]) -> TransferPackageInspection:
        """
        Inspects an offline transfer package, verifying its archive validity, format version,
        and entity summary without applying any live changes to the destination workspace.
        """
        path = Path(package_path).resolve()
        if not path.is_file():
            raise DeviceTransferError(f"Transfer package not found at: {path}")

        try:
            verification = self.backup_engine.verify_backup(path, raise_on_error=False)
        except Exception as err:
            raise DeviceTransferError(f"Corrupt or invalid transfer package: {err}") from err

        # Read manifest from archive
        with tarfile.open(path, "r:*") as tar:
            try:
                manifest_member = tar.getmember("manifest.json")
            except KeyError:
                raise DeviceTransferError("Transfer package is missing root manifest.json")

            f = tar.extractfile(manifest_member)
            if not f:
                raise DeviceTransferError("Failed to extract manifest from transfer package")
            manifest_data = json.loads(f.read().decode("utf-8"))

        format_ver = manifest_data.get("format_version", "unknown")
        is_compatible, ver_warning = self._check_version_compatibility(format_ver)

        records = manifest_data.get("records_summary", {})
        return TransferPackageInspection(
            package_path=str(path),
            is_valid=verification.is_valid or is_compatible,
            format_version=format_ver,
            is_version_compatible=is_compatible,
            version_warning=ver_warning,
            source_platform={
                "os": platform.system(),
                "machine": platform.machine(),
            },
            created_at=manifest_data.get("created_at", ""),
            total_activities=records.get("activity_count", records.get("total_activities", 0)),
            total_checkpoints=records.get("checkpoint_count", records.get("total_checkpoints", 0)),
            total_artifacts=records.get("artifact_snapshot_count", records.get("total_artifacts", 0)),
            total_size_bytes=path.stat().st_size,
            file_manifest_count=len(manifest_data.get("file_manifest", [])),
        )

    def import_transfer_package(
        self,
        package_path: Union[str, Path],
        conflict_strategy: ConflictResolutionStrategy = ConflictResolutionStrategy.REJECT,
        confirm_overwrite: bool = False,
        handle_missing_artifacts: bool = True,
    ) -> TransferImportResult:
        """
        Executes a staged import of an offline transfer package onto this destination device.
        Detects artifacts referenced by source device that do not exist locally, annotating
        them without crashing.
        """
        inspection = self.inspect_package(package_path)
        if not inspection.is_version_compatible:
            raise IncompatibleDeviceVersionError(
                found_version=inspection.format_version,
                supported_version=SUPPORTED_FORMAT_VERSION,
            )

        # Execute staged atomic import via CompleteImportEngine
        import_res = self.import_engine.execute_import(
            archive_path=package_path,
            conflict_strategy=conflict_strategy,
            confirm_overwrite=confirm_overwrite,
        )

        missing_artifacts: List[Dict[str, Any]] = []

        # Audit imported checkpoints for missing local artifact files
        if handle_missing_artifacts:
            missing_artifacts = self._audit_and_reconcile_missing_artifacts()

        return TransferImportResult(
            success=import_res.success,
            import_result=import_res.to_dict(),
            missing_artifacts_detected=missing_artifacts,
            version_note=inspection.version_warning,
        )

    def _check_version_compatibility(self, version_str: str) -> Tuple[bool, Optional[str]]:
        """
        Evaluates format version string against current engine capability.
        Compatible if starting with continuum-backup-v1 or 1.
        """
        if version_str in ("continuum-backup-v1.0", "1.0.0"):
            return True, None
        if version_str.startswith("continuum-backup-v1.") or version_str.startswith("1.0."):
            return True, f"Package format version '{version_str}' is a compatible minor delta."
        return False, f"Major or unsupported version mismatch: '{version_str}'"

    def _audit_and_reconcile_missing_artifacts(self) -> List[Dict[str, Any]]:
        """
        Scans all checkpoints in local store to check if any referenced artifact files
        do not exist on the current device filesystem. Annotates missing references
        gracefully so continuity and timeline queries never fail.
        """
        missing_list: List[Dict[str, Any]] = []
        activities_dir = self.continuum_dir / "activities"
        if not activities_dir.is_dir():
            return missing_list

        for act_dir in activities_dir.iterdir():
            if not act_dir.is_dir():
                continue
            chk_dir = act_dir / "checkpoints"
            if not chk_dir.is_dir():
                continue

            for chk_file in chk_dir.glob("*.json"):
                try:
                    with open(chk_file, "r", encoding="utf-8") as f:
                        chk_data = json.load(f)

                    artifacts = chk_data.get("artifacts", [])
                    modified = False

                    for art in artifacts:
                        # If artifact mode is reference and has a local path
                        art_path_str = art.get("path_or_uri") or art.get("path") or art.get("uri")
                        if art_path_str:
                            p = Path(art_path_str)
                            # Check absolute or relative to workspace
                            exists = p.is_file() or (self.workspace_root / p).is_file()
                            if not exists:
                                if not art.get("missing_on_device"):
                                    art["missing_on_device"] = True
                                    art["device_origin_path"] = art_path_str
                                    modified = True
                                    missing_list.append({
                                        "activity_id": chk_data.get("activity_id"),
                                        "checkpoint_id": chk_data.get("id"),
                                        "artifact_name": art.get("name", "unnamed"),
                                        "referenced_path": art_path_str,
                                        "status": "MISSING_ON_DEVICE_RECONCILED",
                                    })

                    if modified:
                        tmp_file = chk_file.with_suffix(".tmp")
                        with open(tmp_file, "w", encoding="utf-8") as f:
                            json.dump(chk_data, f, indent=2)
                        tmp_file.replace(chk_file)

                except Exception:
                    continue

        return missing_list
